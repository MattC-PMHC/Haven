export function getDeceasedById(id: string): Deceased | undefined {
  return mockDeceased.find((d) => d.id === id)
}

export function getIntermentsForDeceased(deceasedId: string): Interment[] {
  return mockInterments.filter((i) => i.deceased_id === deceasedId)
}

export function getBookingById(id: string): Booking | undefined {
  return mockBookings.find((b) => b.id === id)
}

export function getDeceasedStats() {
  return {
    total: mockDeceased.length,
    thisYear: mockDeceased.filter((d) => d.date_of_death?.startsWith("2026")).length,
  }
}

export function getBookingStats() {
  const byStatus: Record<string, number> = {}
  for (const b of mockBookings) {
    byStatus[b.status] = (byStatus[b.status] || 0) + 1
  }
  return { total: mockBookings.length, byStatus }
}
